    fi = 0
    while nbytes(t) < 900 and fi < len(FILLERS):
        t += FILLERS[fi % len(FILLERS)]
        fi += 1
    while nbytes(t) > 1000:
        cut = t.rfind("。")
        if cut < 100:
            break
        t = t[:cut + 1]
    templates.append(t)

